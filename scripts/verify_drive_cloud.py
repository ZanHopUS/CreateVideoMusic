"""Two real Drive round-trips of generated, non-personal fixtures only.

Default --plan does not access the network. --execute creates a labelled child
folder under the already configured Drive folder, uploads generated fixture bytes,
then restores into disposable workspaces. Production DB/media/config are not copied
or changed. No remote files are deleted. Raw credentials/evidence stay Git-ignored.
"""

import argparse
import copy
import hashlib
import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services/local-api"))
from amvs.catalog import Catalog
from amvs.domain import ROOT as DOMAIN_ROOT
from amvs.drive import API, Drive
from amvs.drive_backup import DriveBackup
from amvs.drive_restore import DriveRestore
from amvs.media import probe
from amvs.store import Store, contained, digest_file
from test_assets import prepare, prepare_video


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--execute", action="store_true")
    parser.add_argument("--source-workspace", type=Path, default=ROOT / ".local/workspace")
    args = parser.parse_args()
    run = ROOT / ".local/evidence/s6-drive" / str(time.time_ns())
    run.mkdir(parents=True)
    prepare()
    prepare_video()
    store = Store(run / "source")
    inventory = []
    project = json.loads((ROOT / "tests/fixtures/project.json").read_text(encoding="utf-8"))
    project["id"] = "drive-s6-" + run.name
    project["name"] = "S6 generated fixture"
    project["durationTicks"] = 144000
    project["assetRefs"] = []
    for item in project["items"]:
        item["durationTicks"] = 144000
    for name in ("artwork.png", "background.mp4", "control.wav"):
        file = ROOT / ".local/test-assets" / name
        metadata = probe(file)
        extension = metadata.pop("extension")
        sha = digest_file(file)
        target = store.root / "library" / (sha + extension)
        shutil.copyfile(file, target)
        asset = {
            "id": sha,
            "file": target.name,
            "name": name,
            "bytes": target.stat().st_size,
            **metadata,
        }
        store.put_asset(asset)
        project["assetRefs"].append(sha)
        visual = name != "control.wav"
        project["items"].append(
            {
                "id": name.replace(".", "-"),
                "trackId": "background" if visual else "music",
                "type": asset["kind"],
                "assetId": sha,
                "startTicks": 0 if name != "background.mp4" else 72000,
                "durationTicks": 72000 if visual else 144000,
                "sourceStartTicks": 0,
                "speed": {"numerator": 1, "denominator": 1},
                "volume": 0 if visual else 1,
            }
        )
        inventory.append(
            {
                "name": name,
                "bytes": asset["bytes"],
                "sha256": sha,
                "provenance": "generated by scripts/test_assets.py, no personal media",
            }
        )
    store.create(project)
    template = Catalog(store).save_template(
        project, "S6 generated reusable template", ["caption", "artwork-png"]
    )
    production_drive = Drive(args.source_workspace)
    report = {
        "run": run.name,
        "sourceAccountConfigured": production_drive.status()["configured"],
        "sourceAccountConnected": production_drive.status()["connected"],
        "inventory": inventory,
        "projects": 1,
        "templates": 1,
        "uploadBytesPerMediaInventory": sum(i["bytes"] for i in inventory),
        "rounds": [],
        "remoteDeletes": False,
        "productionWorkspaceChanged": False,
        "status": "plan-only",
    }

    def save():
        (run / "results.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
        )

    save()
    if not args.execute:
        production_drive.close()
        print(
            json.dumps(
                {
                    "evidence": str(run.relative_to(ROOT)),
                    **{
                        k: report[k]
                        for k in (
                            "sourceAccountConfigured",
                            "sourceAccountConnected",
                            "projects",
                            "templates",
                            "uploadBytesPerMediaInventory",
                            "status",
                        )
                    },
                }
            )
        )
        return 0
    if not report["sourceAccountConnected"]:
        report["status"] = "blocked-not-connected"
        save()
        production_drive.close()
        print(json.dumps({"status": report["status"], "evidence": str(run.relative_to(ROOT))}))
        return 2
    drive = Drive(store.root)
    drive.data = copy.deepcopy(production_drive.data)
    drive.data["autoSync"] = False
    drive.data["lastBackup"] = None
    production_drive.close()
    try:
        folder_name = "AMVS-S6-generated-" + run.name
        drive.data["folder"] = drive.child_folder(drive.data["folder"], folder_name)
        drive.data["name"] = folder_name
        backup = DriveBackup(drive, store)
        previous = None
        for index in (1, 2):
            if index == 2:
                project = {**project, "name": "S6 generated fixture revision 2"}
                store.update(project["id"], project, 1)
            backup.copy()
            last = drive.status()["lastBackup"]
            assert backup.status()["status"] == "succeeded"
            file_id = last["manifestId"]
            meta = drive.request(
                "GET",
                API + "/" + file_id,
                headers=drive.auth(),
                params={"fields": "size,md5Checksum,parents,trashed"},
            ).json()
            descriptor = {"id": file_id, "bytes": int(meta["size"]), "md5": meta["md5Checksum"]}
            manifest_file = run / f"manifest-{index}.json"
            drive.download(file_id, manifest_file, descriptor["bytes"], descriptor["md5"])
            manifest = json.loads(manifest_file.read_bytes())
            restored = Store(run / f"restored-{index}")
            restore = DriveRestore(drive, restored)
            added = restore.restore(descriptor)
            assert added == 1 and restored.load(project["id"])["project"] == project
            assert (
                restored.load(project["id"])["manualSavedHash"] is None
                and restored.load(project["id"])["dirty"]
            )
            assert Catalog(restored).templates() == [template]
            assert all(
                digest_file(restored.asset_path(restored.assets()[id])) == id
                for id in project["assetRefs"]
            )
            ids = {id: a["fileId"] for id, a in manifest["assets"].items()}
            reused = index == 1 or ids == previous
            assert reused
            local = {**project, "name": "Local working edit must survive repeat restore"}
            restored.update(project["id"], local, 1)
            assert restore.restore(descriptor) == 0
            assert restored.load(project["id"])["project"] == local
            report["rounds"].append(
                {
                    "round": index,
                    "restoredProjects": added,
                    "assetHashesMatched": len(ids),
                    "templateMatched": True,
                    "mediaFileIdsReused": reused,
                    "existingWorkingEditsPreserved": True,
                    "manualDirtyPreserved": True,
                    "manifestSha256": hashlib.sha256(manifest_file.read_bytes()).hexdigest(),
                }
            )
            previous = ids
            save()
            print(json.dumps(report["rounds"][-1]), flush=True)
        report["status"] = "passed-generated-cloud-roundtrips"
        report["remoteFolderLabel"] = folder_name
        report["limitations"] = [
            "same-PC disposable workspaces, not a second PC",
            "no real quota exhaustion/revoke or large-upload interruption",
            "generated media, no new renderer MP4; production render still subject to RAM admission",
        ]
        save()
        print(json.dumps({"status": report["status"], "evidence": str(run.relative_to(ROOT))}))
        return 0
    except Exception as error:
        report["status"] = "failed"
        report["errorType"] = type(error).__name__
        save()
        print(
            json.dumps(
                {
                    "status": "failed",
                    "errorType": type(error).__name__,
                    "evidence": str(run.relative_to(ROOT)),
                }
            )
        )
        return 1
    finally:
        drive.close()
        contained(drive.path, store.root).unlink(missing_ok=True)
        report["disposableCredentialCopyRemoved"] = True
        save()


if __name__ == "__main__":
    assert ROOT == DOMAIN_ROOT
    raise SystemExit(main())
